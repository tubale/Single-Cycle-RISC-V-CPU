`timescale 1ns / 1ps

module cpu_wave_tb;

    reg clk;
    reg reset;

    integer i;


    // =========================================================
    // DUT
    // =========================================================

    cpu dut (
        .clk(clk),
        .reset(reset)
    );


    // =========================================================
    // Clock
    // =========================================================

    initial begin
        clk = 0;
        forever #5 clk = ~clk;
    end


    // =========================================================
    // Waveform
    // =========================================================

    initial begin
        $dumpfile("wave.vcd");
        $dumpvars(0, cpu_wave_tb);
    end


    // =========================================================
    // Main
    // =========================================================

    initial begin

        reset = 1;


        // -----------------------------------------------------
        // Fill instruction memory with NOPs
        // -----------------------------------------------------

        for (i = 0; i < 16384; i = i + 1)
            dut.imem.memory[i] = 32'h00000013;


        // -----------------------------------------------------
        // Load waveform demo
        // -----------------------------------------------------

        $readmemh(
            "waveform_demo.mem",
            dut.imem.memory
        );
        // -----------------------------------------------------
        // Reset
        // -----------------------------------------------------

        repeat (2)
            @(posedge clk);

        reset = 0;


        // -----------------------------------------------------
        // Execute
        // -----------------------------------------------------

        repeat (30)
            @(posedge clk);


        $display("Waveform Demo Complete");

        $finish;

    end

endmodule